#!/usr/bin/env node
// Site translations, gettext style: the English text is the message id.
//   node scripts/i18n.mjs extract   t()/tp()/tn() calls in src -> locales/community.pot
//   node scripts/i18n.mjs compile   locales/*.po -> src/locales.generated.ts (gitignored)
//   node scripts/i18n.mjs check     fail when the template is out of date
// Weblate keeps the .po files in step with the template (msgmerge add-on).
import { readFileSync, readdirSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const SOURCES = ['src'];
const EXTENSIONS = /\.(ts|astro)$/;
const TEMPLATE = 'locales/community.pot';
const OUT = 'src/locales.generated.ts';
const DOMAIN = 'community';
// Offer a language once this share of its strings is translated.
const OFFER_AT = 0.5;
const RTL = new Set(['ar', 'he', 'fa', 'ur', 'ps', 'yi', 'dv', 'ckb', 'ug', 'sd', 'ku_Arab']);

function files(dir) {
  return readdirSync(dir).flatMap(name => {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) return files(path);
    return EXTENSIONS.test(name) && !name.includes('.generated.') ? [path] : [];
  });
}

const STRING = String.raw`(?:'((?:\\.|[^'\\\n])*)'|"((?:\\.|[^"\\\n])*)"|` + '`' + String.raw`((?:\\.|[^` + '`' + String.raw`\\$])*)` + '`)';
const CALL = new RegExp(String.raw`(?<![\w.$])(t|tt|tp|tn)\(\s*` + STRING + String.raw`(?:\s*,\s*` + STRING + ')?', 'g');

function unescape(s) {
  return s.replace(/\\(u\{[0-9a-fA-F]+\}|u[0-9a-fA-F]{4}|x[0-9a-fA-F]{2}|.)/gs, (_, c) =>
    c[0] === 'u' ? String.fromCodePoint(parseInt(c.replace(/[u{}]/g, ''), 16))
      : c[0] === 'x' ? String.fromCharCode(parseInt(c.slice(1), 16))
      : ({ n: '\n', t: '\t', r: '\r', '\n': '' })[c] ?? c);
}

export function extract() {
  const messages = new Map();
  for (const file of SOURCES.flatMap(dir => files(join(ROOT, dir))).sort()) {
    const text = readFileSync(file, 'utf8'), where = relative(ROOT, file);
    for (const m of text.matchAll(CALL)) {
      const id = unescape(m[2] ?? m[3] ?? m[4] ?? '');
      const plural = m[1] === 'tn' ? unescape(m[5] ?? m[6] ?? m[7] ?? '') : '';
      if (!id) continue;
      // A `// i18n: ...` comment on the line above is a note for translators.
      const lineStart = text.lastIndexOf('\n', m.index) + 1;
      const above = text.slice(text.lastIndexOf('\n', lineStart - 2) + 1, lineStart);
      const note = /\/\/\s*i18n:\s*(.*)$/.exec(above.trim())?.[1] ?? '';
      const entry = messages.get(id) ?? { id, plural, notes: new Set(), refs: new Set() };
      if (plural) entry.plural = plural;
      if (note) entry.notes.add(note);
      entry.refs.add(where);
      messages.set(id, entry);
    }
  }
  // Pack permission labels live in a table the app shares.
  const table = join(ROOT, 'src/capabilities.json');
  if (existsSync(table)) for (const [, label] of JSON.parse(readFileSync(table, 'utf8')).capabilities) {
    const entry = messages.get(label) ?? { id: label, plural: '', notes: new Set(), refs: new Set() };
    entry.notes.add('Something a block pack can do, listed on its page'); entry.refs.add('src/capabilities.json');
    messages.set(label, entry);
  }
  const out = [
    '# Blockworked site strings. Generated by scripts/i18n.mjs extract; edit the source, not this file.',
    'msgid ""', 'msgstr ""',
    '"Content-Type: text/plain; charset=UTF-8\\n"',
    '"Content-Transfer-Encoding: 8bit\\n"',
    '"Plural-Forms: nplurals=2; plural=(n != 1);\\n"', '',
  ];
  for (const m of messages.values()) {
    for (const note of m.notes) out.push(`#. ${note}`);
    out.push(`#: ${[...m.refs].join(' ')}`);
    if (/\{[a-zA-Z]+\}/.test(m.id + m.plural)) out.push('#, python-brace-format');
    out.push(`msgid ${quote(m.id)}`);
    if (m.plural) out.push(`msgid_plural ${quote(m.plural)}`, 'msgstr[0] ""', 'msgstr[1] ""');
    else out.push('msgstr ""');
    out.push('');
  }
  return { text: out.join('\n'), count: messages.size };
}

function quote(s) {
  const body = JSON.stringify(s).slice(1, -1);
  if (!s.includes('\n') || s.indexOf('\n') === s.length - 1) return `"${body}"`;
  return '""\n' + s.split(/(?<=\n)/).map(line => `"${JSON.stringify(line).slice(1, -1)}"`).join('\n');
}

/** A gettext catalog: header fields and entries by (context, id). */
export function parsePo(text) {
  const entries = [];
  let entry = null, field = null;
  const flush = () => { if (entry && (entry.msgid !== undefined)) entries.push(entry); entry = null; field = null; };
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line) { flush(); continue; }
    if (line.startsWith('#')) {
      if (entry?.msgid !== undefined) flush();
      entry ??= { msgstr: [] };
      if (line.startsWith('#,')) entry.flags = line.slice(2).split(',').map(s => s.trim());
      if (line.startsWith('#~')) entry.obsolete = true;
      continue;
    }
    const m = /^(msgctxt|msgid_plural|msgid|msgstr(?:\[(\d+)\])?)\s+(".*")$/.exec(line);
    if (m) {
      if (m[1] === 'msgctxt' || (m[1] === 'msgid' && entry?.msgid !== undefined)) { if (entry?.msgid !== undefined) flush(); }
      entry ??= { msgstr: [] };
      field = m[1].startsWith('msgstr') ? ['msgstr', Number(m[2] ?? 0)] : [m[1]];
      set(entry, field, JSON.parse(m[3]));
    } else if (line.startsWith('"') && field) set(entry, field, get(entry, field) + JSON.parse(line));
  }
  flush();
  return entries.filter(e => !e.obsolete);
}
function set(e, [k, i], v) { if (k === 'msgstr') e.msgstr[i] = v; else e[k] = v; }
function get(e, [k, i]) { return k === 'msgstr' ? e.msgstr[i] ?? '' : e[k] ?? ''; }

/** The Plural-Forms expression as JS; only gettext's C subset is accepted. */
export function pluralFunction(header) {
  const expr = /plural\s*=\s*([^;]+);?/.exec(/Plural-Forms:([^\n]*)/i.exec(header)?.[1] ?? '')?.[1]?.trim() ?? '(n != 1)';
  if (!/^[n0-9\s?:&|=!<>%()+\-*/]+$/.test(expr)) throw new Error(`Unexpected plural rule: ${expr}`);
  return `(n: number) => Number(${expr})`;
}

export function compile() {
  const dir = join(ROOT, 'locales');
  const template = parsePo(readFileSync(join(ROOT, TEMPLATE), 'utf8')).filter(e => e.msgid);
  const ids = new Set(template.map(e => key(e)));
  const catalogs = [];
  for (const file of existsSync(dir) ? readdirSync(dir).filter(f => f.endsWith('.po')).sort() : []) {
    const code = file.slice(0, -3);
    if (!/^[a-zA-Z]{2,3}(?:[_@-][a-zA-Z0-9]+)*$/.test(code)) continue;
    const entries = parsePo(readFileSync(join(dir, file), 'utf8'));
    const header = entries.find(e => e.msgid === '')?.msgstr[0] ?? '';
    const messages = {};
    for (const e of entries) {
      if (!e.msgid || (e.flags ?? []).includes('fuzzy') || !ids.has(key(e))) continue;
      // Translations reach HTML, so markup and quotes must come from the English text.
      const risky = (s) => [...s.matchAll(/[<>"`]/g)].map(m => m[0]).sort().join('');
      if (e.msgstr.some(s => risky(s) && risky(s) !== risky(e.msgid))) { console.warn(`${file}: skipped a translation with markup the English text lacks: ${JSON.stringify(e.msgid).slice(0, 60)}`); continue; }
      if (e.msgstr.length && e.msgstr.every(s => s)) messages[key(e)] = e.msgstr;
    }
    const tag = code.replace(/_/g, '-').replace(/@.*/, '');
    let name = code;
    try { name = new Intl.DisplayNames([tag], { type: 'language' }).of(tag) ?? code; } catch {}
    name = name.charAt(0).toLocaleUpperCase(tag) + name.slice(1);
    const complete = template.length ? Object.keys(messages).length / template.length : 0;
    catalogs.push(`  ${JSON.stringify(code)}: { tag: ${JSON.stringify(tag)}, name: ${JSON.stringify(name)}, dir: ${RTL.has(code.split(/[_@-]/)[0]) || RTL.has(code) ? '"rtl"' : '"ltr"'}, offered: ${complete >= OFFER_AT}, complete: ${complete.toFixed(3)}, plural: ${pluralFunction(header)}, messages: ${JSON.stringify(messages)} },`);
  }
  writeFileSync(join(ROOT, OUT), `// Generated by scripts/i18n.mjs compile from locales/*.po. Do not edit.\nimport type { Catalog } from './i18n.ts';\nexport const DOMAIN = ${JSON.stringify(DOMAIN)};\nexport const CATALOGS: Record<string, Catalog> = {\n${catalogs.join('\n')}\n};\n`);
  return catalogs.length;
}
function key(e) { return e.msgctxt ? `${e.msgctxt}\u0004${e.msgid}` : e.msgid; }

const command = process.argv[2];
if (command === 'extract') {
  const { text, count } = extract();
  writeFileSync(join(ROOT, TEMPLATE), text);
  console.log(`${TEMPLATE}: ${count} strings`);
} else if (command === 'compile') {
  console.log(`${OUT}: ${compile()} languages`);
} else if (command === 'check') {
  const { text } = extract();
  if (readFileSync(join(ROOT, TEMPLATE), 'utf8') !== text) {
    console.error(`${TEMPLATE} is out of date. Run: node scripts/i18n.mjs extract`);
    process.exit(1);
  }
} else if (command) {
  console.error('Usage: node scripts/i18n.mjs extract|compile|check');
  process.exit(2);
}
