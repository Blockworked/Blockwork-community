// Builds src/language-catalog.ts from Weblate's own language list, so a picked
// code is one Weblate knows. Native names come from Node's ICU.
//   node scripts/languages.mjs [languages.csv]
import { readFileSync, writeFileSync } from 'node:fs';

const SOURCE = 'https://raw.githubusercontent.com/WeblateOrg/language-data/main/languages.csv';
const CODE = /^[a-z]{2,3}(?:_[A-Z][a-z]{3})?(?:_[A-Z]{2}|_\d{3})?(?:@[a-z]{2,10})?$/;
// Names people search for that neither Weblate nor ICU spell out.
const ALIASES = {
  fa: 'Farsi', zh_Hans: 'Mandarin Chinese simplified', zh_Hant: 'Chinese traditional Taiwan Hong Kong', yue: 'Cantonese',
  pt_BR: 'Brazilian', es_419: 'Latin American Mexican', nb: 'Norwegian Bokmal', nn: 'Norwegian', fil: 'Tagalog', tl: 'Filipino',
  ckb: 'Sorani Kurdish', kmr: 'Kurmanji Kurdish', he: 'Ivrit', el: 'Hellenic', ga: 'Gaelic', gd: 'Gaelic', nl_BE: 'Flemish',
  ms: 'Bahasa Melayu', id: 'Bahasa Indonesia', sw: 'Kiswahili', ca: 'Valencian', ky: 'Kirghiz', ro: 'Moldovan', uk: 'Ukranian',
};

function parse(text) {
  const rows = [];
  for (const line of text.trim().split('\n').slice(1)) {
    const cells = []; let cell = '', quoted = false;
    for (const ch of line) {
      if (ch === '"') quoted = !quoted;
      else if (ch === ',' && !quoted) { cells.push(cell); cell = ''; }
      else cell += ch;
    }
    cells.push(cell);
    rows.push(cells);
  }
  return rows;
}

const text = process.argv[2] ? readFileSync(process.argv[2], 'utf8') : await (await fetch(SOURCE)).text();
const english = new Intl.DisplayNames(['en'], {type: 'language', fallback: 'none'});
const out = [];
for (const [code, name] of parse(text)) {
  // Pseudo and developer locales, and the source language itself, aren't proposals.
  if (!CODE.test(code) || code === 'en' || /_(XA|XB|devel)$/.test(code)) continue;
  const tag = code.replace(/@.*/, '').replace(/_/g, '-');
  let native = '';
  try {
    const own = new Intl.DisplayNames([tag], {type: 'language', fallback: 'none'}).of(tag) ?? '';
    // ICU without data for a language answers in English; that isn't a native name.
    if (own && own !== english.of(tag) && own.toLowerCase() !== name.toLowerCase()) native = own;
  } catch {}
  out.push([code, name, native, ALIASES[code] ?? '']);
}
const base = c => c.split(/[_@]/)[0];
out.sort((a, b) => a[1].localeCompare(b[1], 'en'));
writeFileSync(new URL('../src/language-catalog.ts', import.meta.url), `// Generated by scripts/languages.mjs from Weblate's language list. Don't edit.
// [code, English name, name in the language, other names people search for]
export const LANGUAGES: [string, string, string, string][] = ${JSON.stringify(out).replace(/\],\[/g, '],\n[')};
`);
console.log(`${out.length} languages, ${new Set(out.map(r => base(r[0]))).size} base languages`);
